import uuid
from datetime import datetime
from decimal import Decimal
from typing import Annotated, Literal

from pydantic import BaseModel, Field, model_validator

Amount = Annotated[Decimal, Field(max_digits=12, decimal_places=2)]


class SaleLineIn(BaseModel):
    variant_id: uuid.UUID
    quantity: int = Field(ge=1, le=10_000)
    discount: Annotated[Decimal, Field(ge=0, max_digits=12, decimal_places=2)] = Decimal("0")


class PaymentIn(BaseModel):
    method: Literal["cash", "upi", "card"]
    amount: Annotated[Decimal, Field(gt=0, max_digits=12, decimal_places=2)]
    # UPI transaction id / card approval code, as confirmed by the cashier. Required for non-cash.
    reference: str | None = Field(default=None, max_length=100)

    @model_validator(mode="after")
    def _reference_for_electronic(self) -> "PaymentIn":
        if self.method != "cash" and not (self.reference and self.reference.strip()):
            raise ValueError("A reference is required to record a UPI or card payment")
        return self


class SaleIn(BaseModel):
    # Generated by the client once per sale; retries with the same key return the same sale.
    idempotency_key: uuid.UUID
    store_id: uuid.UUID
    customer_id: uuid.UUID | None = None
    items: list[SaleLineIn] = Field(min_length=1, max_length=200)
    payments: list[PaymentIn] = Field(default_factory=list, max_length=10)


class QuoteIn(BaseModel):
    store_id: uuid.UUID
    customer_id: uuid.UUID | None = None
    items: list[SaleLineIn] = Field(min_length=1, max_length=200)


class SaleItemOut(BaseModel):
    id: uuid.UUID
    variant_id: uuid.UUID
    product_name: str
    variant_label: str
    sku: str
    hsn_code: str | None
    quantity: int
    unit_price: Amount
    discount: Amount
    tax_rate: Amount
    taxable_value: Amount
    cgst: Amount
    sgst: Amount
    igst: Amount
    line_total: Amount

    model_config = {"from_attributes": True}


class SalePaymentOut(BaseModel):
    id: uuid.UUID
    method: str
    amount: Amount
    status: str
    reference: str | None

    model_config = {"from_attributes": True}


class SaleOut(BaseModel):
    id: uuid.UUID
    invoice_number: str
    store_id: uuid.UUID
    customer_id: uuid.UUID | None
    sold_at: datetime
    place_of_supply: str
    is_interstate: bool
    discount_total: Amount
    taxable_total: Amount
    cgst_total: Amount
    sgst_total: Amount
    igst_total: Amount
    round_off: Amount
    grand_total: Amount
    items: list[SaleItemOut]
    payments: list[SalePaymentOut]
    replayed: bool = False  # true when an idempotent retry returned an existing sale


class QuoteLine(BaseModel):
    variant_id: uuid.UUID
    product_name: str
    variant_label: str
    quantity: int
    unit_price: Amount
    discount: Amount
    tax_rate: Amount
    line_total: Amount


class SaleQuote(BaseModel):
    """What the sale would come to, so the cashier can take the exact amount."""

    place_of_supply: str
    is_interstate: bool
    lines: list[QuoteLine]
    discount_total: Amount
    taxable_total: Amount
    cgst_total: Amount
    sgst_total: Amount
    igst_total: Amount
    round_off: Amount
    grand_total: Amount


class SaleSummary(BaseModel):
    id: uuid.UUID
    invoice_number: str
    sold_at: datetime
    customer_id: uuid.UUID | None
    grand_total: Amount
